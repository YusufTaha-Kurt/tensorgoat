from __future__ import annotations

import base64
import pickle
import pickletools
import time

from helpers import assert_deterministic, assert_small_artifacts, assert_solvable

from tensorgoat.core.state import State
from tensorgoat.scenarios import get_scenario
from tensorgoat.scenarios.s02_pickle_jar.generate import ALLOWED_GLOBALS, RETURN_VALUE

SID = "s02_pickle_jar"

ALLOWLIST = {("builtins", "print"), ("builtins", "dict")}
# Every opcode the hand-written stream may contain. No INST/OBJ/NEWOBJ/BUILD/EXT*,
# no persistent ids: nothing that could import or construct beyond the allowlist.
ALLOWED_OPCODES = {
    "PROTO",
    "BINUNICODE",
    "SHORT_BINUNICODE",
    "BININT1",
    "GLOBAL",
    "STACK_GLOBAL",
    "TUPLE1",
    "TUPLE2",
    "EMPTY_LIST",
    "MARK",
    "APPENDS",
    "REDUCE",
    "POP",
    "STOP",
}
FORBIDDEN_WORDS = (b"os", b"posix", b"nt", b"subprocess", b"eval", b"exec", b"__import__")
FORBIDDEN_WORDS += (b"socket", b"sys", b"importlib", b"open", b"getattr", b"compile", b"shutil")


def _payload(generated) -> tuple[bytes, str]:
    _, _, ctx = generated(SID)
    return (ctx.workspace / "sentiment_model.pkl").read_bytes(), ctx.flag


def _global_references(payload: bytes) -> list[tuple[str, str]]:
    references = []
    strings: list[str] = []
    for opcode, arg, _ in pickletools.genops(payload):
        if opcode.name in ("GLOBAL", "INST"):
            module, name = str(arg).split(" ", 1)
            references.append((module, name))
        elif opcode.name == "STACK_GLOBAL":
            references.append((strings[-2], strings[-1]))
        if isinstance(arg, str):
            strings.append(arg)
    return references


def test_generate_deterministic(tmp_path):
    assert_deterministic(SID, tmp_path)


def test_solve(isolated_home):
    assert_solvable(SID, isolated_home)


def test_safety_global_allowlist(generated):
    payload, _ = _payload(generated)
    references = _global_references(payload)
    assert ALLOWED_GLOBALS == ALLOWLIST, "the allowlist itself must never grow"
    assert set(references) == ALLOWLIST
    assert len(references) == 2


def test_safety_only_expected_opcodes(generated):
    payload, _ = _payload(generated)
    used = {opcode.name for opcode, _, _ in pickletools.genops(payload)}
    assert used <= ALLOWED_OPCODES, f"unexpected opcodes: {used - ALLOWED_OPCODES}"


def test_safety_no_dangerous_names_anywhere(generated):
    payload, _ = _payload(generated)
    string_args = [
        arg.encode() for _, arg, _ in pickletools.genops(payload) if isinstance(arg, str)
    ]
    # Module/attribute strings must not name anything dangerous.
    short_strings = [value for value in string_args if len(value) < 20]
    for word in FORBIDDEN_WORDS:
        assert word not in short_strings, f"forbidden name {word!r} in the pickle"
    assert b"os\n" not in payload and b"subprocess" not in payload and b"socket" not in payload


def test_loading_prints_only_the_warning_and_never_the_flag(generated, capsys):
    payload, flag = _payload(generated)
    scenario = get_scenario(SID)
    warning = (scenario.path / "assets" / "warning.txt").read_text(encoding="utf-8").strip()

    # Deliberate pickle.loads: the specification requires proving what loading does.
    # The stream is generated by this repository (never downloaded) and is checked
    # against the global and opcode allowlists immediately before it is loaded.
    assert set(_global_references(payload)) == ALLOWLIST
    assert {opcode.name for opcode, _, _ in pickletools.genops(payload)} <= ALLOWED_OPCODES
    result = pickle.loads(payload)

    captured = capsys.readouterr()
    assert captured.out == warning + "\n"
    assert captured.err == ""
    assert flag not in captured.out and "TGOAT{" not in captured.out
    assert base64.b64encode(flag.encode()).decode() not in captured.out
    assert result == RETURN_VALUE == {"model": "fake", "version": 1}
    assert type(result) is dict


def test_warning_text_matches_the_specification():
    scenario = get_scenario(SID)
    warning = (scenario.path / "assets" / "warning.txt").read_text(encoding="utf-8").strip()
    assert warning == (
        "[TensorGoat] You just executed code embedded in an untrusted pickle. "
        "In the real world, this could have been anything. Analyze, don't load."
    )


def test_unintended_flag_is_not_plaintext_and_not_returned(generated):
    payload, flag = _payload(generated)
    assert flag.encode() not in payload
    assert b"TGOAT" not in payload
    # The flag string is pushed and immediately popped: it is dead at run time.
    ops = [(opcode.name, arg) for opcode, arg, _ in pickletools.genops(payload)]
    encoded = base64.b64encode(flag.encode()).decode()
    index = ops.index(("BINUNICODE", encoded))
    assert ops[index + 1][0] == "POP"
    assert sum(1 for _, arg in ops if arg == encoded) == 1


def test_resource_budget(tmp_path):
    state = State(tmp_path / "home")
    started = time.monotonic()
    get_scenario(SID).generate(state)
    assert time.monotonic() - started < 60
    assert_small_artifacts(SID, state)
